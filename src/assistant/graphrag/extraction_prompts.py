_FAILED_INSTRUCTIONS = (
    "Сначала определи контекст фрагмента: incident — произошедший случай с оборудованием, "
    "reference — справочник, руководство или инструкция без случая, other — остальной текст. "
    "Список кодов с типовыми симптомами — reference, даже если рядом с каждым кодом написано «отказ узла». "
    "Для reference и other оставь relations пустым. Если конкретный случай описан, возьми код модели и название "
    "узла только из описания этого случая. Запиши связь, если в тексте утверждается, что узел действительно "
    "отказал или неисправность подтверждена диагностикой. Показанный код ошибки без диагностики недостаточен."
)

_FIELD_ROLES = {
    "BELONGS_TO": ("код модели", "название линейки"),
    "HAS_PART": ("код модели", "артикул детали"),
    "INDICATES": ("код ошибки", "название неисправного узла"),
    "FIXED_BY": ("код ошибки", "код регламента"),
    "REPLACED_BY": ("исходный артикул", "новый артикул"),
    "SUPPLIED_BY": ("артикул детали", "название поставщика"),
    "FAILED": ("код модели", "название реально отказавшего узла"),
}


def relation_prompt(kind: str) -> str:
    if kind == "IS_A":
        return _IS_A_PROMPT
    subject_role, object_role = _FIELD_ROLES[kind]
    subject_type, object_type = RELATION_SIGNATURES[kind]
    instructions = _FAILED_INSTRUCTIONS if kind == "FAILED" else _INSTRUCTIONS[kind]
    example = {
        "entities": [],
        "relations": [{
            "object": f"[{object_role}]", "object_type": object_type,
            "subject": f"[{subject_role}]", "subject_type": subject_type, "type": kind,
        }],
    }
    return (
        f"Извлеки только связи {kind}. {instructions}\n"
        f"В каждой связи subject_type = {subject_type}, subject — {subject_role}. "
        f"object_type = {object_type}, object — {object_role}. type = {kind}.\n"
        "Копируй значения из документа. Каждую подтверждённую связь запиши один раз. "
        "В entities перечисли явно названные сущности, которые не являются концами найденных связей. "
        "Если связей этого типа нет, верни пустой список relations.\n"
        f"Пример формата с условными значениями: {json.dumps(example, ensure_ascii=False, separators=(',', ':'))}\n"
        "В ответе используй данные из текста вместо условных значений. Верни только JSON.\n\nДОКУМЕНТ:\n"
    )
