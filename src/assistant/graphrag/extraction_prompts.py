_FAILED_PROMPT = (
    "Определи, о чём сообщает текст, затем извлеки подтверждённый отказ.\n"
    "\n"
    "Поле context:\n"
    "- incident — есть описанный случай с оборудованием. Текст сообщает о произошедшей поломке, осмотре или "
    "полученном результате диагностики.\n"
    "- reference — справочник кодов, техническое руководство или инструкция без описания конкретного случая.\n"
    "- other — иной текст без описания конкретного случая.\n"
    "\n"
    "Список кодов с типовыми симптомами — reference, даже если рядом с каждым кодом написано «отказ узла» и "
    "указана модель оборудования. Формулировка «при осмотре обнаружили неисправность узла» — incident, если "
    "осмотр описан как состоявшийся. Для смешанного текста выбирай incident, если конкретный случай описан, и "
    "извлекай связи только из описания этого случая.\n"
    "\n"
    "В pairs запиши код модели (model_code) и название узла (component_name) только если текст подтверждает, "
    "что этот узел действительно отказал в описанном случае. Копируй значения из текста. Для reference и "
    "other список pairs пуст. Верни один JSON с полями context и pairs.\n"
    "\n"
    "ДОКУМЕНТ:\n"
)


def relation_prompt(kind: str) -> str:
    if kind == "FAILED":
        return _FAILED_PROMPT
    subject, object_ = PAIR_FIELDS[kind]
    return (
        f"Извлеки только связи {kind}. {_INSTRUCTIONS[kind]}\n"
        f"Копируй значения из документа. Верни JSON: поле pairs содержит список пар с полями {subject} и {object_}. "
        'Каждую подтверждённую пару верни один раз. Если подходящих пар нет, верни {"pairs":[]}.\n\nДОКУМЕНТ:\n'
    )
